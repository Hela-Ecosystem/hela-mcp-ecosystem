#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadInventory, resolveServerDir, selectProfile } from './inventory.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = loadInventory(root);
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'config/tool-catalog.json'), 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const runtimeVersion = data.inventory['hela-runtime'].version;
let check = false, servers = false, profile = 'all';
for (let i = 2; i < process.argv.length; i++) {
  if (process.argv[i] === '--check') check = true;
  else if (process.argv[i] === '--servers') servers = true;
  else if (process.argv[i] === '--profile') {
    profile = process.argv[++i];
    if (!profile || profile.startsWith('--')) throw new Error('Missing documentation profile');
  } else throw new Error(`Unknown argument: ${process.argv[i]}`);
}
const selected = selectProfile(data, profile);
const inventory = {};
for (const [id, spec] of Object.entries(data.inventory)) {
  if (spec.kind === 'runtime') continue;
  const entry = catalog.cells[id];
  if (!entry || entry.version !== spec.version || entry.revision !== spec.revision) throw new Error(`Stale documentation catalog: ${id}`);
  const sizes = entry.variants.map(variant => variant.tools.length);
  inventory[id] = { alias: spec.alias, source: spec.source, dir: spec.dir, scope: spec.scope, role: spec.role,
    entry: spec.entry, version: spec.version, toolsCount: Math.max(...sizes), toolsMin: Math.min(...sizes),
    tools: [...new Set(entry.variants.flatMap(variant => variant.tools.map(tool => tool.name)))].sort(), desc: spec.description };
}
const profiles = Object.fromEntries(data.profiles.map(item => [item.id, { name: item.name, servers: item.servers }]));
const outputs = new Map();
const site = path.join(root, 'docs/site');
const release = { ecosystem: version, runtime: runtimeVersion, cellVersions: [...new Set(Object.values(inventory).map(item => item.version))].sort(), cells: Object.keys(inventory).length };
outputs.set(path.join(site, 'release-data.js'), '// Generated by scripts/generate-docs.mjs; edit the canonical inventory/catalog instead.\n' +
  'globalThis.HELA_DOCS_DATA = ' + JSON.stringify({ release, inventory, profiles }, null, 2) + ';\n');
outputs.set(path.join(root, 'docs/current-versions.md'), '# Current versions and tool surfaces\n\n' +
  `Generated from package metadata, inventory, and the schema catalog. Ecosystem **${version}**; runtime **${runtimeVersion}**.\n\n` +
  Object.entries(inventory).map(([id, item]) => `- **${item.alias}** (\`${id}\`): server **${item.version}**, ${item.toolsMin === item.toolsCount ? item.toolsCount : item.toolsMin + '–' + item.toolsCount} canonical tools; [source](https://github.com/Hela-Ecosystem/${item.source}).`).join('\n') +
  '\n\nCounts vary with declared features. Runtime adds `hela.pipe` and an agent alias when available. Profiles choose eligible cells, not an eager startup count. Historical release notes/snapshots keep their original versions.\n');

for (const directory of [site, path.join(site, 'id')]) {
  for (const name of fs.readdirSync(directory).filter(name => name.endsWith('.html'))) {
    const file = path.join(directory, name);
    let text = fs.readFileSync(file, 'utf8');
    const id = directory.endsWith('/id');
    const label = `v${version} · Runtime ${runtimeVersion} · ${release.cells} ${id ? 'SEL' : 'CELLS'}`;
    text = text.replace(/(<div class="doc-brand-meta">)[^<]*(<\/div>)/g, `$1${label}$2`);
    text = text.replace(/(placeholder="(?:Search|Cari)) (?:292|293|347) /g, '$1 ');
    if (name === 'architecture.html') {
      for (const [cell, info] of Object.entries(inventory)) {
        const pattern = new RegExp('(<span class="server-card-id">' + cell + ' ·.*?)(</span></div>)', 'g');
        const count = info.toolsMin === info.toolsCount ? info.toolsCount : `${info.toolsMin}–${info.toolsCount}`;
        text = text.replace(pattern, (_, header, ending) => header.replace(/(?: · v\d+\.\d+\.\d+)? · [^<>]+$/, ` · v${info.version} · ${count} ${id ? 'alat' : 'tools'}`) + ending);
        const section = new RegExp('(<section class="server-card" aria-labelledby="srv-' + cell.slice(5) + '">[\\s\\S]*?<p class="tool-list">)[^<]*(</p>)');
        text = text.replace(section, (_, start, end) => start + info.tools.join(', ') + end);
      }
    }
    const prefix = id ? '../' : '';
    const app = `<script src="${prefix}app.js?v=${version}"></script>`;
    const generated = `<script src="${prefix}release-data.js?v=${version}"></script>`;
    text = text.replace(/<script src="(?:\.\.\/)?app\.js(?:\?[^"<>]*)?"><\/script>/g, app);
    text = text.replace(/<script src="(?:\.\.\/)?release-data\.js(?:\?[^"<>]*)?"><\/script>/g, generated);
    if (text.includes(app) && !text.includes(generated)) text = text.replace(app, generated + '\n  ' + app);
    if (!id && name === 'index.html') {
      text = text.replace('10 MCP servers, 292 tools:', '10 MCP servers with feature-dependent tools:');
      if (text.includes('"softwareVersion":')) text = text.replace(/"softwareVersion":\s*"[^"]*"/, `"softwareVersion": "${version}"`);
      else text = text.replace('"applicationCategory": "DeveloperApplication",', `"applicationCategory": "DeveloperApplication",\n        "softwareVersion": "${version}",`);
    }
    outputs.set(file, text);
  }
}
const appFile = path.join(site, 'app.js');
const app = fs.readFileSync(appFile, 'utf8');
outputs.set(appFile, app.replace(/\/\/ hela:inventory:start[\s\S]*?\/\/ hela:inventory:end/,
  '// hela:inventory:start\nconst { inventory: INVENTORY, profiles: PROFILES } = globalThis.HELA_DOCS_DATA;\n// hela:inventory:end'));
const readmeFile = path.join(root, 'README.md');
outputs.set(readmeFile, fs.readFileSync(readmeFile, 'utf8').replace(/Current source snapshot: \*\*v[\d.]+\*\*, with runtime \*\*[\d.]+\*\*/,
  `Current source snapshot: **v${version}**, with runtime **${runtimeVersion}**`).replace(/--snapshot v[\d.]+/g, `--snapshot v${version}`));

if (servers) {
  for (const id of selected.servers) {
    const spec = data.inventory[id], item = inventory[id];
    const dir = resolveServerDir(spec, root);
    const repository = [dir, path.dirname(dir)].find(candidate => fs.existsSync(path.join(candidate, 'README.md')));
    if (!repository) throw new Error(`Missing server documentation: ${id}`);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    if (pkg.version !== item.version) throw new Error(`Documentation/package version mismatch: ${id}`);
    const count = item.toolsMin === item.toolsCount ? String(item.toolsCount) : `${item.toolsMin}–${item.toolsCount} (feature-dependent)`;
    const banner = `<!-- hela:version:start -->\n**MCP server:** \`${id}\` · **Version:** \`${item.version}\` · **Canonical tools:** ${count}. [Current tool reference](docs/TOOLS.md).\n<!-- hela:version:end -->`;
    const file = path.join(repository, 'README.md');
    let text = fs.readFileSync(file, 'utf8');
    text = text.includes('<!-- hela:version:start -->')
      ? text.replace(/<!-- hela:version:start -->[\s\S]*?<!-- hela:version:end -->/, banner)
      : text.replace(/^(# [^\n]+\n)/, '$1\n' + banner + '\n');
    outputs.set(file, text);
    const tools = new Map(catalog.cells[id].variants.flatMap(variant => variant.tools).map(tool => [tool.name, tool]));
    const lines = [`# ${item.alias}: canonical tools`, '', `Server version **${item.version}**. Generated from the ecosystem schema catalog; regenerate with \`npm run docs:generate -- --servers\` in the ecosystem checkout.`, '',
      'Only names advertised by `tools/list` are listed here. Older aliases in migration examples are not additional tools. Runtime namespace prefixes are optional and do not change these server-local names.', ''];
    for (const tool of [...tools.values()].sort((a, b) => a.name.localeCompare(b.name))) {
      const conditional = catalog.cells[id].variants.some(variant => !variant.tools.some(candidate => candidate.name === tool.name));
      lines.push(`## \`${tool.name}\`${conditional ? ' (conditional)' : ''}`, '', (tool.description ?? '').replace(/\s+/g, ' ').trim(), '');
      const actions = tool.inputSchema.properties?.action?.enum;
      if (actions) lines.push('Actions: ' + actions.map(action => `\`${action}\``).join(', ') + '.', '');
    }
    outputs.set(path.join(repository, 'docs/TOOLS.md'), lines.join('\n'));
  }
}
let changed = 0;
for (const [file, content] of outputs) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
  if (check) throw new Error(`Stale generated documentation: ${path.relative(root, file)}`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  changed++;
}
console.log(check ? `Documentation metadata matches ${version} / runtime ${runtimeVersion}` : `Generated ${changed} documentation files`);
