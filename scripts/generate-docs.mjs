#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadInventory, resolveServerDir, selectProfile } from './inventory.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = loadInventory(root);
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'config/tool-catalog.json'), 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
const runtimeVersion = data.inventory['hela-runtime'].version;
let check = false, servers = false, profile = 'all';
for (let i = 2; i < process.argv.length; i++) {
  if (process.argv[i] === '--check') check = true;
  else if (process.argv[i] === '--servers') servers = true;
  else if (process.argv[i] === '--profile') {
    profile = process.argv[++i];
    if (!profile || profile.startsWith('--')) throw new Error('Missing documentation profile');
  } else throw new Error(`Unknown argument: ${process.argv[i]}`);
}
const selected = selectProfile(data, profile);
const outputs = new Map();
const installerSource = fs.readFileSync(path.join(root, 'scripts/installation.mjs'), 'utf8');
const installerHelp = fs.readFileSync(path.join(root, 'scripts/install.mjs'), 'utf8').match(/const help = `([\s\S]*?)`;/)?.[1] ?? '';
const flagMap = (declaration, source) => {
  const match = source.match(declaration);
  if (!match) throw new Error('Unable to read installer flag map');
  return [...match[1].matchAll(/\[['"](--?[a-z][a-z0-9-]*)['"],\s*['"]([A-Za-z][A-Za-z0-9]*)['"]\]/g)].map(item => [item[1], item[2]]);
};
const installerFlags = [
  ...flagMap(/const values = new Map\(\[([\s\S]*?)\]\);/, installerSource).map(([flag, name]) => [flag, name, true]),
  ...flagMap(/const booleans = new Map\(\[([\s\S]*?)\]\);/, installerSource).map(([flag, name]) => [flag, name, false]),
  ...[...installerSource.matchAll(/booleans\.set\(['"](--?[a-z][a-z0-9-]*)['"],\s*['"]([A-Za-z][A-Za-z0-9]*)['"]\)/g)].map(item => [item[1], item[2], false]),
  ['--nix', 'mode', false],
];
const flagDescriptions = new Map([...installerHelp.matchAll(/^[ \t]{2}(--?[a-z][a-z0-9-]*)(?:[ \t]+[^\r\n \t]+)?[ \t]{2,}([^\r\n]+)$/gm)].map(item => [item[1], item[2].trim()]));
const flagRows = [...new Map(installerFlags.map(([flag, name, takesValue]) => [flag, { flag, name, takesValue }])).values()]
  .map(({ flag, name, takesValue }) => {
    const value = takesValue ? ' VALUE' : '';
    const description = flagDescriptions.get(flag) ?? ({ '--nix': 'Alias for `--mode nix`.', '-h': 'Alias for `--help`.',
      '--profile': 'Select one of the eight canonical profiles.', '--mode': 'Select the installation mode.',
      '--system': 'Target system hint: `any`, `gui`, or `headless`.', '--transport': 'Runtime transport: stdio or HTTP.',
      '--url': 'Doctor URL for a running HTTP endpoint.', '--json': 'Emit doctor output as JSON.',
      '--without-system-deps': 'Skip tmux probing and installation.' }[flag] ?? `Installer option parsed as \`${name}\`.`);
    return `| \`${flag}${value}\` | ${description} |`;
  }).join('\n');
const flagTable = `<!-- hela:installer-flags:start -->\n<!-- Generated by scripts/generate-docs.mjs from scripts/installation.mjs. -->\n| Flag | Description |\n| --- | --- |\n${flagRows}\n<!-- hela:installer-flags:end -->`;
const installationFile = path.join(root, 'docs/installation.md');
let installationDoc = fs.readFileSync(installationFile, 'utf8');
if (!/<!-- hela:installer-flags:start -->[\s\S]*?<!-- hela:installer-flags:end -->/.test(installationDoc)) throw new Error('Missing generated installer flag markers in docs/installation.md');
outputs.set(installationFile, installationDoc.replace(/<!-- hela:installer-flags:start -->[\s\S]*?<!-- hela:installer-flags:end -->/, flagTable));
const inventory = {};
for (const [id, spec] of Object.entries(data.inventory)) {
  if (spec.kind === 'runtime') continue;
  const entry = catalog.cells[id];
  if (!entry || entry.version !== spec.version || entry.revision !== spec.revision) throw new Error(`Stale documentation catalog: ${id}`);
  const sizes = entry.variants.map(variant => variant.tools.length);
  if (!spec.license) throw new Error(`Missing licence declaration: ${id}`);
  inventory[id] = { alias: spec.alias, source: spec.source, dir: spec.dir, scope: spec.scope, role: spec.role,
    entry: spec.entry, version: spec.version, license: spec.license, toolsCount: Math.max(...sizes), toolsMin: Math.min(...sizes),
    tools: [...new Set(entry.variants.flatMap(variant => variant.tools.map(tool => tool.name)))].sort(), desc: spec.description };
}
const profiles = Object.fromEntries(data.profiles.map(item => [item.id, { name: item.name, servers: item.servers }]));
const site = path.join(root, 'docs/site');
/**
 * The suite is MIT, but six of the ten cells it installs are GPL-3.0-or-later, so a
 * bare "MIT LICENSE" footer told readers the opposite of what a dev-workspace install
 * actually puts on disk. Derive the footer from the inventory licences instead, so it
 * follows the cells rather than a literal nobody remembers to edit.
 */
const cellLicenses = [...new Set(Object.values(inventory).map(item => item.license))].sort();
const licenceUrl = { 'MIT': 'https://opensource.org/license/mit', 'GPL-3.0-or-later': 'https://www.gnu.org/licenses/gpl-3.0.html' };
const licenceUrls = JSON.stringify([licenceUrl.MIT, ...new Set(Object.values(inventory)
  .map(item => item.license).filter(value => value !== 'MIT').map(value => licenceUrl[value] ?? value))]);
const cellNames = list => list.map(item => item.alias.replace(/^HeLa /, ''));
const gplCells = Object.values(inventory).filter(item => item.license !== 'MIT');
const mitCells = Object.values(inventory).filter(item => item.license === 'MIT');
const alwaysInstalled = gplCells.filter(item => data.profiles.every(profile => profile.servers.includes(item.id)));
/**
 * The legal pages state which cells are copyleft, which every profile installs, and what
 * that means for redistribution. That sentence used to be hand-written, so a seventh GPL
 * cell would have left it lying; build it from the inventory instead.
 */
const licenceParagraph = (language) => {
  const join = list => cellNames(list).join(', ');
  if (language === 'id') {
    const universal = alwaysInstalled.length
      ? ` Setiap profil memasang sedikitnya ${alwaysInstalled.length} sel ${gplCells[0]?.license ?? 'non-MIT'} (${join(alwaysInstalled)}), sehingga instalasi HeLa menempatkan kode tersebut di mesin Anda dengan ketentuan lisensinya sendiri.`
      : '';
    return `<p>Repositori ini — installer, runtime, konfigurasi, dan dokumentasi — didistribusikan di bawah <a href="https://github.com/Hela-Ecosystem/hela-mcp-ecosystem/blob/master/LICENSE" target="_blank" rel="noopener noreferrer">Lisensi MIT</a> (hak cipta 2026 Azzar). Sepuluh sel adalah proyek upstream terpisah dengan lisensinya masing-masing: ${gplCells.length} berlisensi ${gplCells[0]?.license ?? 'non-MIT'} (${join(gplCells)}) dan ${mitCells.length} berlisensi MIT (${join(mitCells)}).${universal} Lisensi MIT di atas tidak mengubah lisensi kode ${gplCells[0]?.license ?? 'non-MIT'}; sublisensi, distribusi, atau penjualan sel tersebut tunduk pada lisensinya — baca LICENSE tiap sel sebelum mendistribusikan ulang. Materi situs mengikuti ketentuan MIT kecuali dinyatakan lain.</p>`;
  }
  const universal = alwaysInstalled.length
    ? ` Every profile installs at least ${alwaysInstalled.length} of the ${gplCells[0]?.license ?? 'non-MIT'} cells (${join(alwaysInstalled)}), so installing HeLa places that code on your machine under its own terms.`
    : '';
  return `<p>This repository — the installer, runtime, configuration and documentation — is released under the <a href="https://github.com/Hela-Ecosystem/hela-mcp-ecosystem/blob/master/LICENSE" target="_blank" rel="noopener noreferrer">MIT License</a> (copyright 2026 Azzar). The ten cell servers are separate upstream projects under their own licences: ${gplCells.length} are ${gplCells[0]?.license ?? 'non-MIT'} (${join(gplCells)}) and ${mitCells.length} are MIT (${join(mitCells)}).${universal} The MIT grant above does not relicense ${gplCells[0]?.license ?? 'non-MIT'} code, and sublicensing, distribution or sale of those cells is governed by their licences — read each cell LICENSE before redistributing. Site content follows the MIT terms unless stated otherwise.</p>`;
};

const licenseBlend = cellLicenses.map(value => value.replace(/-or-later$/, '')).join(' + ');
const footerLicense = language => language === 'id'
  ? `SUITE MIT · SEL ${licenseBlend} · AZZAR`
  : `MIT SUITE · ${licenseBlend} CELLS · AZZAR`;
/**
 * Say plainly which cells are copyleft and which of those every profile installs, so a
 * reader deciding whether HeLa fits their licence policy does not have to open ten
 * repositories to find out. Derived, so it follows the inventory and the profiles.
 */
const copyleft = Object.entries(inventory).filter(([, item]) => item.license.startsWith('GPL'));
const universal = Object.entries(profiles).reduce((shared, [, profile]) =>
  shared.filter(id => profile.servers.includes(id)), Object.keys(inventory));
const names = entries => entries.map(([, item]) => item.alias.replace(/^HeLa /, ''));
const licensingNote = (language) => {
  const always = copyleft.filter(([id]) => universal.includes(id));
  if (language === 'id') {
    return `<strong>Lisensi.</strong> Suite ini MIT, tetapi setiap sel memakai lisensinya sendiri: `
      + `${copyleft.length} sel berlisensi GPL-3.0-or-later (${names(copyleft).join(', ')}), sisanya MIT. `
      + (always.length ? `${names(always).join(' dan ')} termasuk dalam setiap profil, jadi setiap pemasangan menyertakan kode GPL-3.0-or-later. ` : '')
      + `Lisensi tiap sel tercantum pada kartunya di bawah.`;
  }
  return `<strong>Licensing.</strong> This suite is MIT, but each cell keeps its own licence: `
    + `${copyleft.length} are GPL-3.0-or-later (${names(copyleft).join(', ')}) and the rest are MIT. `
    + (always.length ? `${names(always).join(' and ')} ship in every profile, so every install includes GPL-3.0-or-later code. ` : '')
    + `Each card below states its cell's licence.`;
};
/**
 * The runtime card and the on-demand guide describe the runtime in prose, which the
 * per-cell rewrite never touched: it skipped `kind === 'runtime'`, so a literal like
 * "runtime 1.2.1" survived while the label said 1.3.2. Keep those sentences derived
 * from the inventory too, so `--check` fails when they drift.
 */
const runtimeProse = (text) => text
  .replace(/(\b(?:Optional runtime|Runtime opsional)\s+)\d+\.\d+\.\d+/g, `$1${runtimeVersion}`)
  .replace(/(Runtime\s+\*\*)\d+\.\d+\.\d+(\*\*)/g, `$1${runtimeVersion}$2`);
const release = { ecosystem: version, runtime: runtimeVersion, cellVersions: [...new Set(Object.values(inventory).map(item => item.version))].sort(), cells: Object.keys(inventory).length };
outputs.set(path.join(site, 'release-data.js'), '// Generated by scripts/generate-docs.mjs; edit the canonical inventory/catalog instead.\n' +
  'globalThis.HELA_DOCS_DATA = ' + JSON.stringify({ release, inventory, profiles }, null, 2) + ';\n');
outputs.set(path.join(root, 'docs/current-versions.md'), '# Current versions and tool surfaces\n\n' +
  `Generated from package metadata, inventory, and the schema catalog. Ecosystem **${version}**; runtime **${runtimeVersion}**.\n\n` +
  Object.entries(inventory).map(([id, item]) => `- **${item.alias}** (\`${id}\`): server **${item.version}**, ${item.license}, ${item.toolsMin === item.toolsCount ? item.toolsCount : item.toolsMin + '–' + item.toolsCount} canonical tools; [source](https://github.com/Hela-Ecosystem/${item.source}).`).join('\n') +
  '\n\nCounts vary with declared features. Runtime adds `hela.pipe` and an agent alias when available. Profiles choose eligible cells, not an eager startup count. Historical release notes/snapshots keep their original versions.\n');

for (const directory of [site, path.join(site, 'id')]) {
  for (const name of fs.readdirSync(directory).filter(name => name.endsWith('.html'))) {
    const file = path.join(directory, name);
    let text = fs.readFileSync(file, 'utf8');
    const id = directory.endsWith('/id');
    const label = `v${version} · Runtime ${runtimeVersion} · ${release.cells} ${id ? 'SEL' : 'CELLS'}`;
    text = text.replace(/(<div class="doc-brand-meta">)[^<]*(<\/div>)/g, `$1${label}$2`);
    text = text.replace(/(placeholder="(?:Search|Cari)) (?:292|293|347) /g, '$1 ');
    text = text.replace(/(<footer class="doc-footer"><span>)[^<]*(<\/span>)/g, `$1${footerLicense(id ? 'id' : 'en')}$2`);
    if (name === 'architecture.html') {
      for (const [cell, info] of Object.entries(inventory)) {
        const pattern = new RegExp('(<span class="server-card-id">' + cell + ' ·.*?)(</span></div>)', 'g');
        const count = info.toolsMin === info.toolsCount ? info.toolsCount : `${info.toolsMin}–${info.toolsCount}`;
        text = text.replace(pattern, (_, header, ending) => header.replace(/(?: · v\d+\.\d+\.\d+)? · [^<>]+$/, ` · v${info.version} · ${count} ${id ? 'alat' : 'tools'}`) + ending);
        const section = new RegExp('(<section class="server-card" aria-labelledby="srv-' + cell.slice(5) + '">[\\s\\S]*?<p class="tool-list">)[^<]*(</p>)');
        text = text.replace(section, (_, start, end) => start + info.tools.join(', ') + end);
        text = text.replace(/(<p class="admonition" id="licensing">)[\s\S]*?(<\/p>)/, `$1${licensingNote(id ? 'id' : 'en')}$2`);
        const licenseLabel = id ? 'lisensi' : 'license';
        const repoLine = new RegExp('(<section class="server-card" aria-labelledby="srv-' + cell.slice(5) + '">[\\s\\S]*?<p class="server-card-id">)([\\s\\S]*?)(</p>)');
        text = text.replace(repoLine, (_, start, body, end) =>
          start + body.replace(/\s*·\s*(?:license|lisensi) <code>[^<]*<\/code>\s*$/, '') + ` · ${licenseLabel} <code>${info.license}</code>` + end);
        const siteDescription = data.inventory[cell].siteDescription?.[id ? 'id' : 'en'];
        if (siteDescription) {
          const description = new RegExp('(<section class="server-card" aria-labelledby="srv-' + cell.slice(5) + '">[\\s\\S]*?<div class="server-card-body">\\s*<p>)[\\s\\S]*?(</p>)');
          text = text.replace(description, (_, start, end) => start + siteDescription + end);
        }
      }
    }
    const prefix = id ? '../' : '';
    const app = `<script src="${prefix}app.js?v=${version}"></script>`;
    const generated = `<script src="${prefix}release-data.js?v=${version}"></script>`;
    text = text.replace(/<script src="(?:\.\.\/)?app\.js(?:\?[^"<>]*)?"><\/script>/g, app);
    text = text.replace(/<script src="(?:\.\.\/)?release-data\.js(?:\?[^"<>]*)?"><\/script>/g, generated);
    if (text.includes(app) && !text.includes(generated)) text = text.replace(app, generated + '\n  ' + app);
    if (!id && name === 'index.html') {
      text = text.replace('10 MCP servers, 292 tools:', '10 MCP servers with feature-dependent tools:');
      if (text.includes('"softwareVersion":')) text = text.replace(/"softwareVersion":\s*"[^"]*"/, `"softwareVersion": "${version}"`);
      else text = text.replace('"applicationCategory": "DeveloperApplication",', `"applicationCategory": "DeveloperApplication",\n        "softwareVersion": "${version}",`);
    }
    let next = runtimeProse(text);
    if (name === 'terms.html') {
      if (!/<!-- hela:license:start -->[\s\S]*?<!-- hela:license:end -->/.test(next)) {
        throw new Error('Missing generated licence markers in docs/site/terms.html');
      }
      next = next.replace(/<!-- hela:license:start -->[\s\S]*?<!-- hela:license:end -->/,
        `<!-- hela:license:start -->\n        ${licenceParagraph(id ? 'id' : 'en')}\n        <!-- hela:license:end -->`);
    }
    next = next.replace(/"license":\s*\[[^\]]*\]/, `"license": ${licenceUrls}`);
    outputs.set(file, next);
  }
}
const llmsFile = path.join(site, 'llms.txt');
if (fs.existsSync(llmsFile)) {
  const llms = fs.readFileSync(llmsFile, 'utf8');
  const line = `- License: this repository (installer, runtime, configuration, docs) is MIT. The ${Object.keys(inventory).length} cell servers are separate projects: ${gplCells.length} ${gplCells[0]?.license ?? 'non-MIT'} (${cellNames(gplCells).join(', ')}), ${mitCells.length} MIT (${cellNames(mitCells).join(', ')}). ${alwaysInstalled.length ? `Every profile installs at least ${alwaysInstalled.length} of those ${gplCells[0]?.license ?? 'non-MIT'} cells; ` : ''}Read each cell LICENSE before redistributing.`;
  let nextLlms = llms.replace(/^- License: .*$/m, line);
  // Tool counts in prose are derived, not retyped (economy: a cell that gains a
  // tool used to break the docs test on a hand-written number).
  for (const [id, entry] of Object.entries(inventory)) {
    const display = id.replace(/^hela-/, '').replace(/^./, (c) => c.toUpperCase());
    const pattern = new RegExp(`(HeLa ${display} \\([^)\\n]*?, )\\d+ tools\\)`, 'g');
    nextLlms = nextLlms.replace(pattern, (match, head) => `${head}${entry.toolsCount} tools)`);
  }
  outputs.set(llmsFile, nextLlms);
}
for (const name of ['on-demand-runtime.md']) {
  const file = path.join(root, 'docs', name);
  outputs.set(file, runtimeProse(fs.readFileSync(file, 'utf8')));
}
const appFile = path.join(site, 'app.js');
const app = fs.readFileSync(appFile, 'utf8');
outputs.set(appFile, app.replace(/\/\/ hela:inventory:start[\s\S]*?\/\/ hela:inventory:end/,
  '// hela:inventory:start\nconst { inventory: INVENTORY, profiles: PROFILES } = globalThis.HELA_DOCS_DATA;\n// hela:inventory:end'));
const readmeFile = path.join(root, 'README.md');
outputs.set(readmeFile, fs.readFileSync(readmeFile, 'utf8').replace(/Current source snapshot: \*\*v[\d.]+\*\*, with runtime \*\*[\d.]+\*\*/,
  `Current source snapshot: **v${version}**, with runtime **${runtimeVersion}**`).replace(/--snapshot v[\d.]+/g, `--snapshot v${version}`));

if (servers) {
  for (const id of selected.servers) {
    const spec = data.inventory[id], item = inventory[id];
    const dir = resolveServerDir(spec, root);
    const repository = [dir, path.dirname(dir)].find(candidate => fs.existsSync(path.join(candidate, 'README.md')));
    if (!repository) throw new Error(`Missing server documentation: ${id}`);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    if (pkg.version !== item.version) throw new Error(`Documentation/package version mismatch: ${id}`);
    const count = item.toolsMin === item.toolsCount ? String(item.toolsCount) : `${item.toolsMin}–${item.toolsCount} (feature-dependent)`;
    const banner = `<!-- hela:version:start -->\n**MCP server:** \`${id}\` · **Version:** \`${item.version}\` · **Canonical tools:** ${count}. [Current tool reference](docs/TOOLS.md).\n<!-- hela:version:end -->`;
    const file = path.join(repository, 'README.md');
    let text = fs.readFileSync(file, 'utf8');
    text = text.includes('<!-- hela:version:start -->')
      ? text.replace(/<!-- hela:version:start -->[\s\S]*?<!-- hela:version:end -->/, banner)
      : text.replace(/^(# [^\n]+\n)/, '$1\n' + banner + '\n');
    outputs.set(file, text);
    const tools = new Map(catalog.cells[id].variants.flatMap(variant => variant.tools).map(tool => [tool.name, tool]));
    const lines = [`# ${item.alias}: canonical tools`, '', `Server version **${item.version}**. Generated from the ecosystem schema catalog; regenerate with \`npm run docs:generate -- --servers\` in the ecosystem checkout.`, '',
      (id === 'hela-mitosis' ? 'With `MITOSIS_EXTERNAL_ORCHESTRATOR` set, only the [passive subset](../README.md#passive-mode-external-orchestrators) is advertised. ' : '')
        + 'Only names advertised by `tools/list` are listed here. Older aliases in migration examples are not additional tools. Runtime namespace prefixes are optional and do not change these server-local names.', ''];
    for (const tool of [...tools.values()].sort((a, b) => a.name.localeCompare(b.name))) {
      const conditional = catalog.cells[id].variants.some(variant => !variant.tools.some(candidate => candidate.name === tool.name));
      lines.push(`## \`${tool.name}\`${conditional ? ' (conditional)' : ''}`, '', (tool.description ?? '').replace(/\s+/g, ' ').trim(), '');
      const actions = tool.inputSchema.properties?.action?.enum;
      if (actions) lines.push('Actions: ' + actions.map(action => `\`${action}\``).join(', ') + '.', '');
    }
    outputs.set(path.join(repository, 'docs/TOOLS.md'), lines.join('\n'));
  }
}
let changed = 0;
for (const [file, content] of outputs) {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
  if (check) throw new Error(`Stale generated documentation: ${path.relative(root, file)}`);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  changed++;
}
console.log(check ? `Documentation metadata matches ${version} / runtime ${runtimeVersion}` : `Generated ${changed} documentation files`);
